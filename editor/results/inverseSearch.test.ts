import { describe, expect, it } from 'vitest';
import { blockSourceLocation } from './inverseSearch';
import { serializeTable } from './table/latex';
import { createTable } from './table/model';

describe('inverse search in one block', () => {
  it('finds a grouped table header rather than the same word in its caption', () => {
    const lines = [
      '\\begin{table}',
      '\\caption{HarmBench results for all models.}',
      '\\begin{tabular}{lcc}',
      'Method & \\multicolumn{1}{c}{\\textbf{HarmBench}} & AdvBench \\\\',
      '\\end{tabular}',
      '\\end{table}',
    ];
    const start = lines[3].indexOf('HarmBench');
    expect(blockSourceLocation(lines.join('\n'), { word: 'HarmBench', context: 'HarmBench', rowContext: 'Method HarmBench AdvBench' }))
      .toEqual({ line: 4, start, end: start + 9 });
  });

  it('uses only the selected block source, without consulting another block', () => {
    expect(blockSourceLocation('\\caption{Other results.}', { word: 'HarmBench', context: 'HarmBench' })).toBeNull();
    expect(blockSourceLocation('\\section{Results}\nOur method improves accuracy.', { word: 'Results', context: '1 Results' }))
      .toEqual({ line: 1, start: 9, end: 16 });
  });

  it('preserves source line numbers including table cache comments', () => {
    const source = '% portfolio-table:v1 cached\n\\begin{tabular}{lc}\nModel & HarmBench \\\\\n\\end{tabular}';
    expect(blockSourceLocation(source, { word: 'HarmBench', context: 'Model HarmBench' }))
      .toEqual({ line: 3, start: 8, end: 17 });
  });

  it('selects the clicked repeated word in a header, such as Shift B rather than Shift A', () => {
    const source = 'Method & In-domain & Shift A & Shift B & Shift C \\\\';
    const row = 'Method In-domain Shift A Shift B Shift C';
    expect(blockSourceLocation(source, {
      word: 'Shift', context: 'Shift B', contextOffset: 2,
      rowContext: row, rowContextOffset: row.indexOf('Shift B') + 2,
    })).toEqual({ line: 1, start: source.indexOf('Shift B'), end: source.indexOf('Shift B') + 5 });
  });

  it('selects an integer cell in a table generated by the visual editor, including colored cells', () => {
    const table = createTable(1, 3);
    for (const [column, text] of ['Ours', '12', '34'].entries()) {
      table.cells[0][column]!.text = text;
      table.cells[0][column]!.background = '#4E42BA';
    }
    const source = serializeTable(table);
    const prefix = source.slice(0, source.indexOf('12\n'));
    const start = prefix.length - prefix.lastIndexOf('\n') - 1;
    expect(blockSourceLocation(source, { word: '12', context: '12', rowContext: 'Ours 12 34', rowContextOffset: 6 }))
      .toEqual({ line: prefix.split('\n').length, start, end: start + 2 });
  });

  it('uses the clicked column to distinguish repeated integer cells, without selecting the row label', () => {
    const source = 'Ours & 12 & 12 & 34 \\\\';
    const row = 'Ours 12 12 34';
    const start = source.lastIndexOf('12');
    expect(blockSourceLocation(source, {
      word: '12', context: '12', rowContext: row, rowContextOffset: row.lastIndexOf('12') + 1,
    })).toEqual({ line: 1, start, end: start + 2 });
  });

  it('selects literal table data when another cell renders a math command', () => {
    const lines = ['\\begin{tabular}{lcc}', 'Ours & 12 & $\\alpha$ \\\\', '\\end{tabular}'];
    expect(blockSourceLocation(lines.join('\n'), { word: '12', context: '12', rowContext: 'Ours 12 α' }))
      .toEqual({ line: 2, start: 7, end: 9 });
  });

  it('distinguishes repeated data on either side of a rendered math command', () => {
    const row = 'Ours & 12 & $\\alpha$ & 12 \\\\';
    const source = `\\begin{tabular}{lccc}\n${row}\n\\end{tabular}`;
    const context = 'Ours 12 α 12';
    const start = row.lastIndexOf('12');
    expect(blockSourceLocation(source, {
      word: '12', context: '12', rowContext: context, rowContextOffset: context.lastIndexOf('12') + 1,
    })).toEqual({ line: 2, start, end: start + 2 });
  });

  it('preserves signs and percentage suffixes when selecting the clicked numeric value', () => {
    const source = 'Delta & $12.5$ & $-12.5$ & $+12.5$ & 12.5\\% \\\\';
    const row = 'Delta 12.5 −12.5 +12.5 12.5%';
    for (const [word, literal] of [['−12.5', '-12.5'], ['+12.5', '+12.5'], ['12.5%', '12.5\\%']]) {
      const start = source.indexOf(literal);
      expect(blockSourceLocation(source, {
        word, context: word, rowContext: row, rowContextOffset: row.indexOf(word) + 2,
      })).toEqual({ line: 1, start, end: start + literal.length });
    }
  });

  it.each(['0.2', '1,234.56', '-1.2e-3'])('selects an entire %s value in formatted table data', (value) => {
    const source = `Ours & \\textbf{${value}} & $74.8 \\pm 0.2$ \\\\`;
    const start = source.indexOf(value);
    expect(blockSourceLocation(source, { word: value, context: value, rowContext: `Ours ${value} 74.8 ± 0.2`, rowContextOffset: 6 }))
      .toEqual({ line: 1, start, end: start + value.length });
  });

  it.each(['-1,234.56', '+1,234,567.89\\%'])('preserves signs and suffixes on the grouped value %s', (literal) => {
    const value = literal.replace('\\%', '%');
    const source = `Ours & ${literal} & 56 \\\\`;
    const start = source.indexOf(literal);
    expect(blockSourceLocation(source, { word: value, context: value, rowContext: `Ours ${value} 56` }))
      .toEqual({ line: 1, start, end: start + literal.length });
  });

  it('allows a decimal followed by sentence punctuation without matching part of another value', () => {
    const source = 'Other 112.5 and -12.5. Our score is 12.5.';
    const start = source.lastIndexOf('12.5');
    expect(blockSourceLocation(source, { word: '12.5', context: 'Our score is 12.5.' }))
      .toEqual({ line: 1, start, end: start + 4 });
  });
});
